import { analyzeJava, testTargets } from './javasource.ts';
import { exceptionMessage, normalizeOutput, output } from './learning.ts';
import type { Check, Project, Run, RunRequest, SourceFile } from './types';

/** Generated class that evaluates a method-call test. Its name marks it as tooling, not student code. */
export const HARNESS_CLASS = 'TraceLabCall__';
export const RESULT_MARKER = '\u001eTRACELAB_RESULT ';
export const isHarnessFile = (name: string) => name.split('/').at(-1) === `${HARNESS_CLASS}.java`;
export const isCallTest = (check: Check) => check.kind === 'call';

const IDENT = /^[A-Za-z_$][\w$]*$/;

/**
 * Prefixes a bare call such as `sum(xs)` with its class when that class declares a method of that name,
 * so students can write the call the way they would inside the class.
 */
export function qualifyCall(call: string, target: string, files: SourceFile[]): string {
  const bare = call.trim().match(/^([A-Za-z_$][\w$]*)\s*\(/);
  if (!bare || bare[1] === 'new') return call.trim();
  const type = testTargets(files).find(t => t.qualified === target);
  return type?.methods.some(m => m.name === bare[1]) ? `${type.name}.${call.trim()}` : call.trim();
}

function harnessSource(packageName: string, expression: string): string {
  return `${packageName ? `package ${packageName};\n\n` : ''}// Generated by TraceLab to run a method test. It is not part of your project.
public class ${HARNESS_CLASS} {
    public static void main(String[] args) {
        String result;
        try {
            Object value = ${expression};
            result = "value " + show(value);
        } catch (Throwable thrown) {
            result = "throws " + thrown.getClass().getName();
        }
        System.out.flush();
        System.out.println();
        System.out.println("${RESULT_MARKER.replace('\u001e', '\\u001e')}" + result);
    }

${SHOW_SOURCE}
}
`;
}

/** Java source of the harness's `show` method, which prints a value the way expected values are written. */
export const SHOW_SOURCE = `    static String show(Object value) {
        if (value == null) return "null";
        if (value instanceof String text) return "\\"" + text.replace("\\\\", "\\\\\\\\").replace("\\"", "\\\\\\"").replace("\\n", "\\\\n") + "\\"";
        if (value instanceof Character c) return "'" + c + "'";
        if (value.getClass().isArray()) {
            StringBuilder out = new StringBuilder("[");
            for (int i = 0; i < java.lang.reflect.Array.getLength(value); i++) out.append(i == 0 ? "" : ", ").append(show(java.lang.reflect.Array.get(value, i)));
            return out.append("]").toString();
        }
        if (value instanceof java.util.Map<?, ?> map) {
            StringBuilder out = new StringBuilder("{");
            for (java.util.Map.Entry<?, ?> entry : map.entrySet()) out.append(out.length() == 1 ? "" : ", ").append(show(entry.getKey())).append("=").append(show(entry.getValue()));
            return out.append("}").toString();
        }
        if (value instanceof java.util.Collection<?> items) {
            StringBuilder out = new StringBuilder("[");
            for (Object item : items) out.append(out.length() == 1 ? "" : ", ").append(show(item));
            return out.append("]").toString();
        }
        return String.valueOf(value);
    }`;

/** Problems with a test definition that would stop it from running. */
export function testProblems(check: Check, project: Project): string[] {
  const problems: string[] = [];
  if (!check.name.trim()) problems.push('Give the test a name.');
  if (isCallTest(check)) {
    if (!check.call?.trim()) problems.push('Enter the call to evaluate, such as sum(new int[]{1, 2}).');
    else if (/[\r\n]/.test(check.call)) problems.push('Write the call on one line.');
    else if (/[;{}]/.test(check.call.replace(/new\s+[\w$.<>]+\s*(\[\s*\])+\s*\{[^;]*\}/g, ''))) problems.push('Enter a single expression, not statements. Array literals like new int[]{1, 2} are fine.');
    if (!check.target || !testTargets(project.files).some(t => t.qualified === check.target)) problems.push('Choose the class that defines the method.');
    if (!check.expectedOutput.trim()) problems.push('Enter the expected value, or “throws ExceptionName”.');
    if (project.files.length >= 20) problems.push('Method tests need one free file slot; this project already has 20 files.');
  }
  return problems;
}

/** The run request for a test: the program itself, or the program plus a generated harness class. */
export function requestForTest(project: Project, check: Check, base: RunRequest): RunRequest {
  if (!isCallTest(check)) return { ...base, stdin: check.stdin };
  const target = check.target ?? '';
  const packageName = target.includes('.') ? target.slice(0, target.lastIndexOf('.')) : '';
  const file: SourceFile = { name: `${packageName ? `${packageName.replace(/\./g, '/')}/` : ''}${HARNESS_CLASS}.java`, content: harnessSource(packageName, qualifyCall(check.call ?? '', target, project.files)) };
  return { ...base, stdin: check.stdin, files: [...base.files.filter(f => !isHarnessFile(f.name)), file], mainClass: packageName ? `${packageName}.${HARNESS_CLASS}` : HARNESS_CLASS };
}

/** One expression in a batch harness. Batches evaluate many calls in one JVM, each isolated by try/catch. */
export type BatchCase = { id: number; expression: string };
export type BatchResult = { id: number; status: 'value' | 'throws' | 'unfinished' | 'invalid'; value: string; detail?: string };

/** A harness that evaluates each case in turn. `lines` maps a source line to its case, to attribute javac errors. */
export function batchHarness(packageName: string, cases: BatchCase[]): { file: SourceFile; lines: Map<number, number> } {
  const head = `${packageName ? `package ${packageName};\n\n` : ''}// Generated by TraceLab to run method tests. It is not part of your project.
public class ${HARNESS_CLASS} {
    public static void main(String[] args) {
`;
  const lines = new Map<number, number>();
  let line = head.split('\n').length;
  const body = cases.map(c => { lines.set(line++, c.id); return `        run(${c.id}, () -> ${c.expression});\n`; }).join('');
  const tail = `    }

    interface Thunk__ { Object get() throws Throwable; }

    static void run(int id, Thunk__ call) {
        String result;
        try {
            result = "value " + show(call.get());
        } catch (Throwable thrown) {
            result = "throws " + thrown.getClass().getName();
        }
        System.out.flush();
        System.out.println();
        System.out.println("${RESULT_MARKER.replace('\u001e', '\\u001e')}" + id + " " + result);
    }

${SHOW_SOURCE}
}
`;
  const folder = packageName ? `${packageName.replace(/\./g, '/')}/` : '';
  return { file: { name: `${folder}${HARNESS_CLASS}.java`, content: head + body + tail }, lines };
}

/** A plain (unrecorded) run of a batch harness. */
export function batchRequest(base: RunRequest, packageName: string, cases: BatchCase[]): { request: RunRequest; lines: Map<number, number> } {
  const { file, lines } = batchHarness(packageName, cases);
  return { request: { ...base, mode: 'run', files: [...base.files.filter(f => !isHarnessFile(f.name)), file], mainClass: packageName ? `${packageName}.${HARNESS_CLASS}` : HARNESS_CLASS }, lines };
}

/** Results printed by a batch harness, keyed by case id. Values are written as tests expect them (`3`, `"a"`, `throws ArithmeticException`). */
export function batchResults(stdout: string): Map<number, BatchResult> {
  const out = new Map<number, BatchResult>();
  for (const raw of stdout.split(/\r?\n/)) {
    if (!raw.startsWith(RESULT_MARKER)) continue;
    const m = raw.slice(RESULT_MARKER.length).match(/^(\d+) (value|throws) (.*)$/);
    if (!m) continue;
    out.set(Number(m[1]), { id: Number(m[1]), status: m[2] as 'value' | 'throws', value: m[2] === 'throws' ? `throws ${m[3].replace(/^java\.lang\./, '')}` : m[3] });
  }
  return out;
}

/** The expression a method test evaluates, with the class prefixed for bare calls. */
export const testExpression = (check: Check, files: SourceFile[]) => qualifyCall(check.call ?? '', check.target ?? '', files);

/** Explains a javac error in a test's generated call. */
export function harnessErrorDetail(message: string): string {
  if (/void/.test(message)) return 'This method returns void, so there is no value to compare. Test what it prints with a program-output test instead.';
  if (/non-static/.test(message)) return 'This is an instance method. Create an object in the call, for example new Counter().next().';
  return `The call does not compile: ${message.split('\n')[0]}`;
}

/** Pass/fail for a method test evaluated in a batch. */
export function batchOutcome(check: Check, result: BatchResult): TestOutcome {
  if (result.status === 'invalid' || result.status === 'unfinished') return { passed: false, detail: result.detail ?? 'No result' };
  const passed = valuesMatch(check.expectedOutput, result.value);
  return { passed, detail: passed ? `Returned ${result.value}` : `Expected ${check.expectedOutput.trim()}, got ${result.value}` };
}

/** The value line printed by the harness, e.g. `value 3` or `throws java.lang.ArithmeticException`. */
export function callResult(run: Run): string | null {
  const text = output(run, 'stdout');
  const at = text.lastIndexOf(RESULT_MARKER);
  return at < 0 ? null : text.slice(at + RESULT_MARKER.length).split(/\r?\n/)[0].trim();
}

const unquote = (text: string) => /^"(?:[^"\\]|\\.)*"$/.test(text) ? text.slice(1, -1).replace(/\\n/g, '\n').replace(/\\"/g, '"').replace(/\\\\/g, '\\') : null;
const numeric = (text: string) => /^[+-]?(?:\d+\.?\d*(?:[eE][+-]?\d+)?|\.\d+|NaN|Infinity)$/.test(text) ? Number(text) : null;

/** Compares an expected value with the harness result, allowing quotes to be omitted and tiny floating-point error. */
export function valuesMatch(expected: string, actual: string): boolean {
  const e = expected.trim(), a = actual.trim();
  if (e === a) return true;
  const thrown = e.match(/^throws\s+([\w$.]+)$/i);
  if (thrown) return a.startsWith('throws ') && (a.slice(7) === thrown[1] || a.slice(7).split('.').at(-1) === thrown[1].split('.').at(-1));
  if (a.startsWith('throws ')) return false;
  const text = unquote(a);
  if (text !== null && (e === text || unquote(e) === text)) return true;
  const charValue = a.match(/^'(.)'$/)?.[1];
  if (charValue !== undefined && e === charValue) return true;
  const x = numeric(e), y = numeric(a);
  if (x !== null && y !== null) return x === y || (Number.isFinite(x) && Number.isFinite(y) && Math.abs(x - y) <= 1e-9 * Math.max(1, Math.abs(x), Math.abs(y)));
  return false;
}

export type TestOutcome = { passed: boolean; detail: string };

/** Pass/fail and a one-line explanation for a finished test run. */
export function evaluateTest(run: Run, check: Check): TestOutcome {
  const reason = run.events.at(-1)?.stopReason;
  if (isCallTest(check)) {
    const harnessError = run.events.find(e => e.kind === 'diagnostic' && e.severity === 'error' && isHarnessFile(e.file ?? ''));
    if (harnessError) return { passed: false, detail: harnessErrorDetail(harnessError.message ?? '') };
    if (reason === 'compile-error') return { passed: false, detail: 'The project does not compile. Fix the errors under Problems first.' };
    const result = callResult(run);
    if (result === null) return { passed: false, detail: reason === 'completed' ? 'The call finished without producing a result.' : stopDetail(run) };
    const actual = result.startsWith('value ') ? result.slice(6) : result;
    const passed = valuesMatch(check.expectedOutput, actual);
    return { passed, detail: passed ? `Returned ${actual}` : `Expected ${check.expectedOutput.trim()}, got ${actual.replace(/^throws java\.lang\./, 'throws ')}` };
  }
  if (reason === 'completed' && normalizeOutput(output(run, 'stdout')) === normalizeOutput(check.expectedOutput)) return { passed: true, detail: 'Output matches' };
  if (reason !== 'completed') return { passed: false, detail: stopDetail(run) };
  return { passed: false, detail: `Expected ${JSON.stringify(normalizeOutput(check.expectedOutput))}, got ${JSON.stringify(normalizeOutput(output(run, 'stdout')))}` };
}

const STOP_DETAILS: Record<string, string> = {
  'compile-error': 'Compile error', 'step-limit': 'Step limit reached', timeout: 'Time limit reached', cancelled: 'Stopped',
  'runtime-error': 'Exited with an error', 'unsupported-concurrency': 'Multiple threads', 'trace-limit': 'Trace too large', 'worker-error': 'Runner error',
  'output-limit': 'Stopped after 32,768 characters of output, which usually means an endless loop',
};
function stopDetail(run: Run): string {
  const reason = run.events.at(-1)?.stopReason ?? '';
  const exception = run.events.findLast(e => e.exception && !e.exception.caught);
  if (reason === 'exception' && exception) {
    const message = exceptionMessage(run, exception);
    return `${exception.exception!.type.split('.').at(-1)}${message ? `: ${message}` : ''}`;
  }
  return STOP_DETAILS[reason] ?? 'Runner error';
}

/** Describes a test in one line for tables. */
export function describeTest(check: Check): { kind: string; given: string; expects: string } {
  if (isCallTest(check)) return { kind: `Method · ${(check.target ?? '').split('.').at(-1)}`, given: check.call ?? '', expects: check.expectedOutput };
  return { kind: 'Output', given: check.stdin ? JSON.stringify(check.stdin) : 'no input', expects: JSON.stringify(check.expectedOutput) };
}

/** Classes whose source declares a method with this name; used to suggest a target. */
export function classesDeclaring(method: string, files: SourceFile[]): string[] {
  return testTargets(files).filter(t => t.methods.some(m => m.name === method)).map(t => t.qualified);
}

